export function optionsWithExistingValue(options: readonly (string | FixedOption)[], currentValue: unknown): FixedOption[] {
  const current = typeof currentValue === "string" ? currentValue.trim() : "";
  const normalized = options.map((option) => typeof option === "string"
    ? { value: option, label: option === "Basico" ? "Básico" : option }
    : option);
  return current && !normalized.some((option) => option.value === current)
    ? [{ value: current, label: `${current} (valor existente)` }, ...normalized]
    : normalized;
}
